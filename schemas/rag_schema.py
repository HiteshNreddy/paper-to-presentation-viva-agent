"""
schemas/rag_schema.py — Pydantic models for the RAG pipeline.

Encapsulates:
- RAGResponse: Complete outcome of a RAG question-answering operation,
  including the grounded answer, supporting page sources, relevance assessment,
  retrieval decision, and error indicators.
"""

from __future__ import annotations

from pydantic import BaseModel, Field
from schemas.summary_schema import RetrievedSource


class RetrievalAssessment(BaseModel):
    """Detailed relevance assessment of retrieved chunks."""

    chunk_count_retrieved: int = Field(..., ge=0, description="Total chunks fetched from vector store.")
    chunk_count_accepted: int = Field(..., ge=0, description="Chunks passing relevance and distance thresholds.")
    average_distance: float = Field(..., description="Average cosine distance of accepted chunks.")
    relevance_score: float = Field(..., ge=0.0, le=1.0, description="Normalized relevance confidence (0.0 to 1.0).")
    is_sufficient: bool = Field(..., description="Whether context is sufficient to ground an answer.")
    refinement_triggered: bool = Field(default=False, description="Whether query refinement was triggered.")
    explanation: str = Field(..., description="Human-readable explanation of the assessment.")


class RAGResponse(BaseModel):
    """
    Structured outcome of the RAG generation pipeline.

    Guarantees that:
    1. The answer is accompanied by verified source pages.
    2. Hallucination flags and context sufficiency are explicitly tracked.
    3. The retrieval decision and strategy are auditable for viva examination.
    """

    question: str = Field(..., description="The user's query.")
    answer: str = Field(..., description="The grounded answer generated by the LLM.")
    sources: list[RetrievedSource] = Field(
        default_factory=list,
        description="List of verified source pages grounding the answer.",
    )
    assessment: RetrievalAssessment = Field(
        ...,
        description="Detailed relevance assessment and filtering metrics.",
    )
    strategy_used: str = Field(
        ...,
        description="Strategy used: 'canonical', 'user_refined', 'broad_fallback', or 'direct_no_retrieval'.",
    )
    is_grounded: bool = Field(
        ...,
        description="True if the response is strictly grounded in retrieved paper content.",
    )
    has_sufficient_context: bool = Field(
        ...,
        description="True if relevant chunks were found; False if question is outside paper scope.",
    )
    error: str | None = Field(
        default=None,
        description="Error message if generation or retrieval encountered a failure.",
    )

    model_config = {"frozen": False}

